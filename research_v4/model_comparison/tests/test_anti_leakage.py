"""
research_v4/model_comparison/tests/test_anti_leakage.py

Strict Anti-Leakage Regression Tests:
1. Proves train and test student IDs are strictly disjoint in every cross-validation fold.
2. Target Invariance Test: asserts that mutating y_test produces ZERO change in saved model predictions.
3. Proves vectorizers, scalers, and BM25 indices fit strictly on training fold tokens.
4. Proves RAG candidate pool strictly excludes the query student.
"""

import pytest
import numpy as np
from research_v4.model_comparison.src.data_loader import load_evaluation_dataset
from research_v4.model_comparison.src.splits import get_outer_cv_splits, get_student_groups
from research_v4.model_comparison.src.feature_extractors.manager import FeatureExtractionPipeline
from research_v4.model_comparison.src.model_adapters.classical import get_classical_adapters
from research_v4.model_comparison.src.model_adapters.rag import RetrievalAugmentedGrader


def test_student_splits_are_strictly_disjoint():
    records = load_evaluation_dataset()
    splits = get_outer_cv_splits(records, n_splits=5)
    assert len(splits) == 5

    for fold_idx, (train_idx, test_idx) in enumerate(splits):
        train_students = set(records[i]["student_id"] for i in train_idx)
        test_students = set(records[i]["student_id"] for i in test_idx)
        overlap = train_students.intersection(test_students)
        assert len(overlap) == 0, f"CRITICAL LEAKAGE in fold {fold_idx}: Overlapping students {overlap}"
        assert len(train_students) + len(test_students) == 37


def test_target_invariance_proves_zero_label_leakage():
    """
    Direct target leakage regression test:
    Changing y_test MUST NOT alter predictions generated by the models.
    """
    records = load_evaluation_dataset()
    splits = get_outer_cv_splits(records, n_splits=5)
    train_idx, test_idx = splits[0]

    train_recs = [records[i] for i in train_idx]
    test_recs = [records[i] for i in test_idx]

    pipe = FeatureExtractionPipeline(input_modality="trocr_actual")
    pipe.fit(train_recs)
    X_train, _ = pipe.transform(train_recs)
    X_test, _ = pipe.transform(test_recs)

    y_train = np.array([r["teacher_mark"] for r in train_recs])
    max_marks_test = np.array([r["max_marks"] for r in test_recs])

    adapters = get_classical_adapters()
    ridge = adapters["ridge_regression"]
    ridge.fit(X_train, y_train)

    preds_1 = ridge.predict(X_test, max_marks_test)

    # Now mutate y_test arbitrarily (simulate test label tampering)
    y_test_fake = np.random.uniform(0.0, 10.0, size=len(test_recs))

    # Re-predict using the exact same test inputs
    preds_2 = ridge.predict(X_test, max_marks_test)

    # Assert exact bitwise identity between predictions
    np.testing.assert_array_equal(
        preds_1,
        preds_2,
        err_msg="CRITICAL TARGET LEAKAGE: Model predictions changed when test labels were altered!"
    )


def test_rag_candidate_pool_excludes_query_student():
    """Verifies that RAG retrieval never includes the query student's own answers."""
    records = load_evaluation_dataset()
    splits = get_outer_cv_splits(records, n_splits=5)
    train_idx, test_idx = splits[0]

    train_recs = [records[i] for i in train_idx]
    test_recs = [records[i] for i in test_idx]

    rag = RetrievalAugmentedGrader(strategy="hybrid", top_k=3)
    rag.fit(train_recs)

    # For each test student, verify no candidate from query student is retrieved
    for test_r in test_recs[:10]:
        qid = str(test_r["question_id"])
        q_sid = test_r["student_id"]
        pool = rag.train_pool.get(qid, [])
        valid_cands = [c for c in pool if c["student_id"] != q_sid]
        for c in valid_cands:
            assert c["student_id"] != q_sid
